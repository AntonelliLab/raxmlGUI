import { serializeAndCleanError } from './report';

function fenced( value ) {
  return `\`\`\`json
${JSON.stringify( value, null, '  ' )}
\`\`\``;
}

function githubIssueBody( error, activeState ) {
  return `Autogenerated report:
${fenced( serializeAndCleanError( error ) )}

Active state:
${fenced( activeState )}

---

Process: renderer`;
}

export async function reportIssueToGitHub( error ) {
  const { rendererBridge, store } = /** @type {any} */ ( window );
  const body = githubIssueBody( error, store.generateReport() );
  const info = await rendererBridge.debugInfo();
  const url = new URL( 'https://github.com/AntonelliLab/raxmlGUI/issues/new' );
  url.searchParams.set( 'title', error.name );
  url.searchParams.set( 'body', `${body}\n${info}` );
  await rendererBridge.openExternal( url.toString() );
}
