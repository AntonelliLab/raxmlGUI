function newGithubIssueUrl( options = {} ) {
  const { repoUrl: repoUrlOption, user, repo } = options;
  let repoUrl;
  if ( repoUrlOption ) {
    repoUrl = repoUrlOption;
  } else if ( user && repo ) {
    repoUrl = `https://github.com/${user}/${repo}`;
  } else {
    throw new Error( 'You need to specify either the `repoUrl` option or both the `user` and `repo` options' );
  }
  const url = new URL( `${repoUrl}/issues/new` );
  const types = [
    'body',
    'title',
    'labels',
    'template',
    'milestone',
    'assignee',
    'projects',
  ];
  for ( const type of types ) {
    let value = options[type];
    if ( value === undefined ) {
      continue;
    }
    if ( type === 'labels' || type === 'projects' ) {
      if ( !Array.isArray( value ) ) {
        throw new TypeError( `The \`${type}\` option should be an array` );
      }
      value = value.join( ',' );
    }
    url.searchParams.set( type, String( value ) );
  }
  return url.toString();
}
export const is = {
  macos: process.platform === 'darwin',
  linux: process.platform === 'linux',
  windows: process.platform === 'win32',
  main: process.type === 'browser',
  renderer: process.type === 'renderer',
  development: process.env.NODE_ENV === 'development',
  macAppStore: processWithElectron.mas === true,
  windowsStore: processWithElectron.windowsStore === true,
};
export const platform = ( object ) => {
  let platformKey = process.platform;
  if ( is.macos ) {
    platformKey = 'macos';
  } else if ( is.windows ) {
    platformKey = 'windows';
  }
  const fn = platformKey in object
    ? object[platformKey]
    : object.default;
  return typeof fn === 'function'
    ? fn()
    : fn;
};
