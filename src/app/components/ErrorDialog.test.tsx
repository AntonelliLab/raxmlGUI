import { expect, it, vi } from 'vitest';
import { act } from 'react';
import { createRoot } from 'react-dom/client';
import type { RendererBridge } from '../../common/rendererBridge';
import type RunList from '../store/RunList';
import { installBridge } from '../../test/setup';
import ErrorDialog from './ErrorDialog';

it( 'the reload action reloads the window', () => {
  const reload = vi.fn();
  installBridge( { reload } );
  const div = document.createElement( 'div' );
  document.body.appendChild( div );
  const root = createRoot( div );
  // createRoot().render paints on a later tick. act flushes that paint.
  act( () => {
    root.render(
      <ErrorDialog
        error={new Error( 'boom' )}
        onClose={() => {}}
        needReload
      />,
    );
  } );

  const button = Array.from( document.body.querySelectorAll( 'button' ) )
    .find( ( item ) => item.textContent === 'Ignore and reload' )!;
  act( () => {
    button.click();
  } );

  expect( reload ).toHaveBeenCalledTimes( 1 );

  act( () => {
    root.unmount();
  } );
  div.remove();
} );

function renderDialog( error: Error ) {
  const div = document.createElement( 'div' );
  document.body.appendChild( div );
  const root = createRoot( div );
  // createRoot().render paints on a later tick. act flushes that paint.
  act( () => {
    root.render(
      <ErrorDialog
        error={error}
        onClose={() => {}}
      />,
    );
  } );
  return {
    root,
    div,
    button( label: string ) {
      return Array.from( document.body.querySelectorAll<HTMLElement>( 'button, a' ) )
        .find( ( item ) => item.textContent === label )!;
    },
  };
}

it( 'builds the GitHub issue body, then opens it with debug info', async () => {
  const order: string[] = [];
  const info = `raxmlGUI 2.0.18
Electron 45.2.3
darwin 25.6.0
Locale: en-US`;
  window.store = {
    generateReport() {
      order.push( 'body' );
      return { command: 'raxml -s primates.fasta', stdout: '', stderr: '' };
    },
  } as unknown as RunList;
  const debugInfo = vi.fn( async () => {
    order.push( 'debug' );
    return info;
  } );
  const openExternal = vi.fn<RendererBridge['openExternal']>( async () => {
    order.push( 'open' );
  } );
  installBridge( { debugInfo, openExternal } );
  const error = new Error( 'boom\nsecond line' );
  const view = renderDialog( error );
  // Mailto builds its href while painting and also reads the store report.
  order.length = 0;

  await act( async () => {
    view.button( 'Report issue on GitHub' ).click();
  } );

  expect( order ).toEqual( ['body', 'debug', 'open'] );
  expect( debugInfo ).toHaveBeenCalledWith();
  const url = new URL( openExternal.mock.calls[0][0] );
  expect( `${url.origin}${url.pathname}` ).toBe( 'https://github.com/AntonelliLab/raxmlGUI/issues/new' );
  expect( url.searchParams.get( 'title' ) ).toBe( 'Error: boom' );
  const body = url.searchParams.get( 'body' )!;
  expect( body.startsWith( 'Autogenerated report:' ) ).toBe( true );
  expect( body ).toContain( 'boom' );
  expect( body ).toContain( 'raxml -s primates.fasta' );
  expect( body ).toContain( 'Process: renderer' );
  expect( body.endsWith( info ) ).toBe( true );

  act( () => {
    view.root.unmount();
  } );
  view.div.remove();
} );

it( 'the mailto report stays an href', () => {
  const view = renderDialog( new Error( 'boom' ) );
  const link = view.button( 'Report issue on mail' );

  expect( link.tagName ).toBe( 'A' );
  expect( link.getAttribute( 'href' ) ).toMatch( /^mailto:raxmlgui.help@googlemail.com/ );
  expect( link.getAttribute( 'href' ) ).toContain( 'boom' );

  act( () => {
    view.root.unmount();
  } );
  view.div.remove();
} );
