// @ts-nocheck — Jest globals. checkJs has no test runner types.
import React, { act } from 'react';
import { createRoot } from 'react-dom/client';
import ErrorDialog from './ErrorDialog';

it( 'the reload action reloads the window', () => {
  const reload = jest.fn();
  window.rendererBridge = { reload };
  const div = document.createElement( 'div' );
  document.body.appendChild( div );
  const root = createRoot( div );
  // createRoot().render paints on a later tick. act flushes that paint.
  // eslint-disable-next-line testing-library/no-unnecessary-act
  act( () => {
    root.render(
      <ErrorDialog
        error={new Error( 'boom' )}
        onClose={() => {}}
        needReload
      />,
    );
  } );

  const button = [...document.body.querySelectorAll( 'button' )]
    .find( ( item ) => item.textContent === 'Ignore and reload' );
  act( () => {
    button.click();
  } );

  expect( reload ).toHaveBeenCalledTimes( 1 );

  act( () => {
    root.unmount();
  } );
  div.remove();
} );

function renderDialog( error ) {
  const div = document.createElement( 'div' );
  document.body.appendChild( div );
  const root = createRoot( div );
  // createRoot().render paints on a later tick. act flushes that paint.
  // eslint-disable-next-line testing-library/no-unnecessary-act
  act( () => {
    root.render(
      <ErrorDialog
        error={error}
        onClose={() => {}}
      />,
    );
  } );
  return {
    root,
    div,
    button( label ) {
      return [...document.body.querySelectorAll( 'button, a' )]
        .find( ( item ) => item.textContent === label );
    },
  };
}

it( 'builds the GitHub issue body, then opens it with debug info', async () => {
  const order = [];
  const info = `raxmlGUI 2.0.18
Electron 45.2.3
darwin 25.6.0
Locale: en-US`;
  window.store = {
    generateReport() {
      order.push( 'body' );
      return { command: 'raxml -s primates.fasta', stdout: '' };
    },
  };
  const debugInfo = jest.fn( async () => {
    order.push( 'debug' );
    return info;
  } );
  const openExternal = jest.fn( async () => {
    order.push( 'open' );
  } );
  window.rendererBridge = { debugInfo, openExternal };
  const error = new Error( 'boom' );
  const view = renderDialog( error );

  await act( async () => {
    view.button( 'Report issue on GitHub' ).click();
  } );

  expect( order ).toEqual( ['body', 'debug', 'open'] );
  expect( debugInfo ).toHaveBeenCalledWith();
  const url = new URL( openExternal.mock.calls[0][0] );
  expect( `${url.origin}${url.pathname}` ).toBe( 'https://github.com/AntonelliLab/raxmlGUI/issues/new' );
  expect( url.searchParams.get( 'title' ) ).toBe( error.name );
  const body = url.searchParams.get( 'body' );
  expect( body.startsWith( 'Autogenerated report:' ) ).toBe( true );
  expect( body ).toContain( 'boom' );
  expect( body ).toContain( 'raxml -s primates.fasta' );
  expect( body ).toContain( 'Process: renderer' );
  expect( body.endsWith( info ) ).toBe( true );

  act( () => {
    view.root.unmount();
  } );
  view.div.remove();
} );

it( 'the mailto report stays an href', () => {
  window.rendererBridge = {};
  const view = renderDialog( new Error( 'boom' ) );
  const link = view.button( 'Report issue on mail' );

  expect( link.tagName ).toBe( 'A' );
  expect( link.getAttribute( 'href' ) ).toMatch( /^mailto:raxmlgui.help@googlemail.com/ );
  expect( link.getAttribute( 'href' ) ).toContain( 'boom' );

  act( () => {
    view.root.unmount();
  } );
  view.div.remove();
} );
