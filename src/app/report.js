import { serializeError } from 'serialize-error';

// Mirrors clean-stack@3 default filtering. The page cannot import that package (it loads os).
const extractPathRegex = /\s+at.*[(\s](.*)\)?/;
const pathRegex = /^(?:(?:(?:node|(?:(?:node:)?internal\/[\w/]*|.*node_modules\/(?:babel-polyfill|pirates)\/.*)?\w+)(?:\.js)?:\d+:\d+)|native)/;

export const cleanStack = ( stack ) => {
  if ( typeof stack !== 'string' ) {
    return stack;
  }
  return stack
    .replace( /\\/g, '/' )
    .split( '\n' )
    .filter( ( line ) => {
      const pathMatches = line.match( extractPathRegex );
      if ( pathMatches === null || !pathMatches[1] ) {
        return true;
      }
      const match = pathMatches[1];
      if (
        match.includes( '.app/Contents/Resources/electron.asar' )
        || match.includes( '.app/Contents/Resources/default_app.asar' )
      ) {
        return false;
      }
      return !pathRegex.test( match );
    } )
    .filter( ( line ) => line.trim() !== '' )
    .join( '\n' );
};

export const serializeAndCleanError = ( error ) => {
  const err = serializeError( error );
  const stack = error && typeof error.stack === 'string'
    ? error.stack
    : undefined;
  if ( err && typeof err === 'object' && stack ) {
    err.stack = cleanStack( stack );
  }
  return err;
};

const stringify = ( json ) => JSON.stringify( json, null, '  ' );

const createReportBodyForMail = ( error, activeState ) => encodeURI( `Autogenerated report:
${stringify( serializeAndCleanError( error ) )}

Active state:
${stringify( activeState )}

---

Process: renderer` );

export const getMailtoLinkToReportError = ( error ) => {
  const { store } = /** @type {any} */ ( window );
  const activeState = store && typeof store.generateReport === 'function'
    ? store.generateReport()
    : undefined;
  return `mailto:raxmlgui.help@googlemail.com?subject=${encodeURI( error.name )}&body=${createReportBodyForMail( error, activeState )}`;
};
